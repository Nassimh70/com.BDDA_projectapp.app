CREATE OR REPLACE TYPE BODY e_t AS
  MEMBER FUNCTION f RETURN NUMBER IS BEGIN RETURN 1; END;
  MEMBER FUNCTION f(x IN CHAR) RETURN NUMBER IS BEGIN RETURN 2; END;
  MEMBER PROCEDURE p(x IN NUMBER) IS BEGIN DBMS_OUTPUT.PUT_LINE('p=' || x); END;
  MEMBER FUNCTION est(x IN NUMBER) RETURN BOOLEAN IS BEGIN RETURN x = self.id; END;
  STATIC PROCEDURE g(x IN NUMBER) IS BEGIN DBMS_OUTPUT.PUT_LINE('g=' || x); END;
END;
