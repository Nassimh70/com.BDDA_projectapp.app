CREATE OR REPLACE TYPE BODY p_t AS
  MEMBER FUNCTION f RETURN NUMBER IS BEGIN RETURN 1; END;
  MEMBER FUNCTION g RETURN NUMBER IS BEGIN RETURN 2; END;
  MEMBER FUNCTION h(x IN NUMBER) RETURN NUMBER IS BEGIN RETURN x; END;
  MEMBER PROCEDURE p(x IN NUMBER) IS
  BEGIN
    UPDATE p_tab SET id = id WHERE id = SELF.id;
    DBMS_OUTPUT.PUT_LINE('p DML ok pour id='||SELF.id);
  END;
  STATIC PROCEDURE s(x IN NUMBER) IS
  BEGIN
    INSERT INTO p_tab VALUES (p_t(99, tel_vry_type('X'), 0));
    COMMIT;
    DBMS_OUTPUT.PUT_LINE('s INSERT+COMMIT ok');
  END;
END;
