PROMPT ===== F. VARRAY IS NULL + COUNT + TRIM =====
DECLARE
  v tel_vry_type := tel_vry_type('A','B','C');
  w tel_vry_type;
BEGIN
  DBMS_OUTPUT.PUT_LINE('v.COUNT='||v.COUNT||' v.LIMIT='||v.LIMIT||' v.LAST='||v.LAST);
  v.TRIM(1);
  DBMS_OUTPUT.PUT_LINE('apres TRIM v.COUNT='||v.COUNT);
  IF w IS NULL THEN
    DBMS_OUTPUT.PUT_LINE('w IS NULL : TRUE');
  ELSE
    DBMS_OUTPUT.PUT_LINE('w IS NULL : FALSE');
  END IF;
  BEGIN
    DBMS_OUTPUT.PUT_LINE('w.COUNT='||w.COUNT);
  EXCEPTION WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('w.COUNT -> '||SQLERRM);
  END;
END;
