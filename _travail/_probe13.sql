CREATE OR REPLACE TYPE BODY q_t AS
  MEMBER FUNCTION f RETURN NUMBER IS BEGIN RETURN 1; END;
  MEMBER PROCEDURE p(x IN NUMBER) IS
  BEGIN
    UPDATE q_tab SET nom = nom WHERE id = SELF.id;
    DBMS_OUTPUT.PUT_LINE('p DML ok id='||SELF.id||' x='||x);
  END;
  STATIC PROCEDURE s(x IN NUMBER) IS
  BEGIN
    INSERT INTO q_tab VALUES (q_t(99, 'S'));
    COMMIT;
    DBMS_OUTPUT.PUT_LINE('s INSERT+COMMIT ok x='||x);
  END;
END;
/
SHOW ERRORS TYPE BODY q_t

