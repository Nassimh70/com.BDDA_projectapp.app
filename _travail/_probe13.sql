CREATE OR REPLACE TYPE BODY r_t AS
  MEMBER FUNCTION g RETURN NUMBER IS BEGIN RETURN 42; END;
END;
/
CREATE OR REPLACE TYPE BODY q_t AS
  MEMBER FUNCTION f RETURN NUMBER IS
    v r_t := r_t(1);
  BEGIN
    RETURN v.g();
  END;
  MEMBER PROCEDURE p(x IN NUMBER) IS
  BEGIN
    UPDATE q_tab SET nom = nom WHERE id = SELF.id;
  END;
  STATIC PROCEDURE s(x IN NUMBER) IS
  BEGIN
    INSERT INTO q_tab VALUES (q_t(99, 'S'));
    COMMIT;
  END;
END;
