SET SERVEROUTPUT ON SIZE UNLIMITED
SET LINESIZE 200
SET PAGESIZE 100
SET DEFINE OFF
PROMPT *** CARDINALITY AVEC ALIAS ***
SELECT c.num_client, CARDINALITY(c.telephones) AS nb FROM client c ORDER BY 1;
PROMPT *** TABLE() SUR UN VARRAY ***
SELECT c.num_client, COUNT(*) AS nb_lignes, COUNT(t.COLUMN_VALUE) AS nb_renseignes
  FROM client c, TABLE(c.telephones) t
 GROUP BY c.num_client ORDER BY 1;
PROMPT *** TABLE() SUR UNE SEULE LIGNE ***
SELECT COUNT(*) AS nb_total, COUNT(t.COLUMN_VALUE) AS nb_non_null
  FROM TABLE(SELECT telephones FROM client WHERE num_client = 1) t;
PROMPT *** FIN ***
EXIT
